/* ---------------------------------------------------------------------
   P5 · DML y lectura del WAL con pg_walinspect (log de transacciones)
   --------------------------------------------------------------------- */
CREATE EXTENSION IF NOT EXISTS pg_walinspect;

CREATE TEMP TABLE marca (lsn_inicio pg_lsn, xid_dml xid8);
INSERT INTO marca (lsn_inicio) VALUES (pg_current_wal_lsn());

BEGIN;
    UPDATE marca SET xid_dml = pg_current_xact_id();    -- identifica la transacción
    INSERT INTO clientes (cedula, nombre, telefono, correo)
    VALUES ('0607777777', 'Gabriela Ortiz', '0997777777', 'gabriela.ortiz@correo.ec');   -- INSERT
    UPDATE productos SET precio = 9.50 WHERE id_producto = 3;                             -- UPDATE
    DELETE FROM clientes WHERE id_cliente = 6;                                            -- DELETE
COMMIT;

-- P5b · Registros del WAL de esa transacción, con la tabla afectada
SELECT w.start_lsn, w.xid, w.record_type,
       COALESCE(c.relname, 'catálogo del sistema / tabla temporal') AS tabla_afectada,
       left(w.description, 45) AS descripcion
FROM pg_get_wal_records_info((SELECT lsn_inicio FROM marca), pg_current_wal_lsn()) AS w
LEFT JOIN pg_class AS c
       ON c.relfilenode = substring(w.block_ref FROM 'rel \d+/\d+/(\d+)')::oid
      AND c.relnamespace = 'public'::regnamespace
WHERE w.xid::text = (SELECT xid_dml::text FROM marca)
  AND w.resource_manager IN ('Heap', 'Transaction')
ORDER BY w.start_lsn;


/* ---------------------------------------------------------------------
   P6 · UNDO en PostgreSQL (ejecutar P6a y P6b por separado)
   --------------------------------------------------------------------- */
-- P6a · Error dentro de una transacción abierta
BEGIN;
    UPDATE productos SET precio = 0.01;              -- error: todos los precios en 0,01
    SELECT id_producto, nombre, precio AS precio_durante_el_error,
           txid_current_if_assigned() AS transaccion_abierta
    FROM productos ORDER BY id_producto LIMIT 3;
-- (todavía sin COMMIT ni ROLLBACK)

-- P6b · ROLLBACK (UNDO); reemplazar 678 por el número que mostró P6a
ROLLBACK;
SELECT id_producto, nombre, precio AS precio_tras_rollback,
       pg_xact_status('678') AS estado_transaccion_678
FROM productos ORDER BY id_producto LIMIT 3;


/* ---------------------------------------------------------------------
   P7 · Caso práctico: pérdida parcial de datos (después de la copia base)
   --------------------------------------------------------------------- */
-- P7a · Marca previa
CREATE TEMP TABLE marca_error (lsn_antes pg_lsn, xid_error xid8, detalles_antes int);
INSERT INTO marca_error (lsn_antes, detalles_antes)
SELECT pg_current_wal_lsn(), COUNT(*) FROM detalle_ventas;

-- P7b · El error del auxiliar (transacción propia)
BEGIN;
    UPDATE marca_error SET xid_error = pg_current_xact_id();
    DELETE FROM detalle_ventas d
    USING ventas v
    WHERE v.id_venta = d.id_venta
      AND v.fecha_venta < '2026-11-13';                 -- ¡error del auxiliar!
COMMIT;

SELECT detalles_antes, (SELECT COUNT(*) FROM detalle_ventas) AS detalles_despues,
       xid_error AS transaccion_del_error
FROM marca_error;

-- P7c · Búsqueda forense en el WAL: registros de la transacción del error
SELECT w.start_lsn, w.xid AS transaccion, w.record_type,
       COALESCE(c.relname, '-') AS tabla,
       CASE WHEN w.record_type = 'COMMIT' THEN split_part(w.description, ';', 1)
            ELSE left(w.description, 40) END AS detalle
FROM pg_get_wal_records_info((SELECT lsn_antes FROM marca_error), pg_current_wal_lsn()) AS w
LEFT JOIN pg_class AS c
       ON c.relfilenode = substring(w.block_ref FROM 'rel \d+/\d+/(\d+)')::oid
      AND c.relnamespace = 'public'::regnamespace
WHERE w.xid::text = (SELECT xid_error::text FROM marca_error)
  AND w.resource_manager IN ('Heap', 'Transaction')
ORDER BY w.start_lsn;
-- La hora del COMMIT es el valor de recovery_target_time
-- (con recovery_target_inclusive = false: detenerse justo ANTES de ese COMMIT)

-- P7d · Enviar al archivo el segmento WAL que contiene el error
SELECT pg_switch_wal() AS lsn_cierre_segmento;
SELECT pg_sleep(3);
SELECT archived_count, last_archived_wal, last_archived_time, failed_count
FROM pg_stat_archiver;

