CREATE TABLE clientes (
    id_cliente   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula       CHAR(10)      NOT NULL UNIQUE,
    nombre       VARCHAR(100)  NOT NULL,
    telefono     VARCHAR(15),
    correo       VARCHAR(100)
);
CREATE TABLE productos (
    id_producto  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(100)  NOT NULL,
    laboratorio  VARCHAR(60)   NOT NULL,
    precio       NUMERIC(10,2) NOT NULL CHECK (precio > 0),
    stock        INT           NOT NULL CHECK (stock >= 0)
);
CREATE TABLE ventas (
    id_venta     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente   INT           NOT NULL REFERENCES clientes (id_cliente),
    fecha_venta  TIMESTAMP(0)  NOT NULL DEFAULT now(),
    total        NUMERIC(10,2) NOT NULL DEFAULT 0
);
CREATE TABLE detalle_ventas (
    id_detalle      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta        INT           NOT NULL REFERENCES ventas (id_venta),
    id_producto     INT           NOT NULL REFERENCES productos (id_producto),
    cantidad        INT           NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2) NOT NULL
);

